#!/usr/bin/env python3
"""Flatten the src/ modules into src/download.py. See AGENTS.md."""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")
OUT = os.path.join(SRC, "download.py")

# Dependency order: a module must come after the ones it reads from.
MODULES = ["config", "vision", "autonomousroutine", "drivercontrol", "main"]

# Extra builds for vexcom slots: (file, call replacing the final main()).
VARIANTS = [("download_driver.py", "driver()"), ("download_auto.py", "auto_on_button()")]

# `from config import *`, `from vision import cone_detector`, `import config`...
LOCAL_IMPORT = re.compile(r"^\s*(?:from|import)\s+(?:%s)\b" % "|".join(MODULES))

# Kept once, at the very top, rather than repeated per module.
VEX_IMPORT = re.compile(r"^\s*from\s+vex\s+import\s+\*\s*$")

HEADER = """\
# download.py -- GENERATED by build.py, do not edit.
# Built from: %s

from vex import *
"""


def flatten():
    missing = [m for m in MODULES if not os.path.exists(os.path.join(SRC, m + ".py"))]
    if missing:
        sys.exit("build.py: missing module(s): %s" % ", ".join(missing))

    parts = [HEADER % ", ".join(m + ".py" for m in MODULES)]

    for name in MODULES:
        path = os.path.join(SRC, name + ".py")
        kept = []
        for line in open(path).read().split("\n"):
            if LOCAL_IMPORT.match(line) or VEX_IMPORT.match(line):
                continue
            kept.append(line)

        body = "\n".join(kept).strip("\n")
        parts.append(
            "\n\n# ======================== %s ========================\n\n%s\n"
            % (name + ".py", body)
        )

    source = "".join(parts)

    # Catch it here rather than as a line number into a generated file.
    try:
        compile(source, OUT, "exec")
    except SyntaxError as err:
        sys.exit("build.py: flattened output does not parse: line %s: %s"
                 % (err.lineno, err.msg))

    open(OUT, "w").write(source)
    print("build.py: wrote %s (%d lines) from %s"
          % (os.path.relpath(OUT, HERE), len(source.split("\n")), ", ".join(MODULES)))

    # Same program with a fixed entry point, one per brain slot.
    if not source.rstrip().endswith("\nmain()"):
        sys.exit("build.py: main.py must end with main()")
    for name, entry in VARIANTS:
        path = os.path.join(SRC, name)
        open(path, "w").write(source.rstrip()[:-len("main()")] + entry + "\n")
        print("build.py: wrote %s (entry %s)" % (os.path.relpath(path, HERE), entry))
    print("build.py: now hit Download in VEXcode.")


if __name__ == "__main__":
    flatten()
